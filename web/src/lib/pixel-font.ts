export interface PixelTextBitmap {
  width: number;
  height: number;
  on: Uint8Array;
}

export function renderPixelText(text: string, fontHeight: 5 | 10): PixelTextBitmap {
  const scale = fontHeight === 10 ? 2 : 1;
  const glyphs = Array.from(text.toUpperCase()).map((character) => PIXEL_FONT[character] ?? PIXEL_FONT[" "]!);
  const baseWidth = glyphs.length === 0 ? 0 : glyphs.length * 3 + glyphs.length - 1;
  const width = baseWidth * scale;
  const height = 5 * scale;
  const on = new Uint8Array(Math.max(1, width * height));

  glyphs.forEach((glyph, glyphIndex) => {
    const glyphOffset = glyphIndex * 4;
    for (let glyphY = 0; glyphY < 5; glyphY += 1) {
      for (let glyphX = 0; glyphX < 3; glyphX += 1) {
        if (glyph[glyphY]?.[glyphX] !== "#") continue;
        for (let scaleY = 0; scaleY < scale; scaleY += 1) {
          for (let scaleX = 0; scaleX < scale; scaleX += 1) {
            const x = (glyphOffset + glyphX) * scale + scaleX;
            const y = glyphY * scale + scaleY;
            on[y * width + x] = 1;
          }
        }
      }
    }
  });

  return { width, height, on };
}
